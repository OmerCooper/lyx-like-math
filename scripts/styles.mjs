// Builds styles.css: MathLive's fonts (embedded, so the plugin needs no fonts/ folder and no CDN),
// MathLive's layout CSS for formulas drawn outside a math-field (panel buttons), and the plugin's
// own CSS from src/styles.css. Obsidian's community installer downloads only main.js,
// manifest.json and styles.css.
import fs from "fs";
import path from "path";

const MATHLIVE = "node_modules/mathlive/dist";

// url(fonts/NAME.woff2) -> url(data:font/woff2;base64,...)
export function inlineFonts(css, readFont) {
  return css.replace(/url\(fonts\/([^)]+\.woff2)\)/g,
    (_, name) => `url(data:font/woff2;base64,${readFont(name).toString("base64")})`);
}

export function buildStyles() {
  // mathlive-static.css holds the @font-face rules as well as the layout
  const mathlive = fs.readFileSync(path.join(MATHLIVE, "mathlive-static.css"), "utf8");
  return [
    "/* LyX-like Math. Generated by scripts/styles.mjs from src/styles.css: edit that file. */",
    fs.readFileSync("src/styles.css", "utf8").trim(),
    "/* MathLive 0.101.0 (MIT): fonts and static layout */",
    inlineFonts(mathlive, (name) => fs.readFileSync(path.join(MATHLIVE, "fonts", name))),
  ].join("\n") + "\n";
}

export function writeStyles() {
  fs.writeFileSync("styles.css", buildStyles());
}
